#!/usr/bin/env python3
"""Render the CurbCut AI backlog documents from source data.

Usage:
    python3 scripts/render_backlog.py

Writes backlog/EPICS.md, ISSUES.md, PRS.md, COMMITS.md and METRICS.md.
Standard library only; no network access.
"""

from __future__ import annotations

import collections
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "backlog"))

from data_issues import EPICS, ISSUES, STD  # noqa: E402
from data_prs import PRS  # noqa: E402
from data_commits import ROOT_COMMITS, commit_rows  # noqa: E402

OUT = ROOT / "backlog"

HEADER = "<!-- Generated by scripts/render_backlog.py. Do not edit by hand. -->\n"


def w(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8")


def table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |"]
    out.append("| " + " | ".join("---" for _ in headers) + " |")
    for row in rows:
        out.append("| " + " | ".join(row) + " |")
    return "\n".join(out)


def epics_by_key() -> dict[str, dict]:
    return {e["key"]: e for e in EPICS}


def issues_by_epic() -> dict[str, list[dict]]:
    grouped: dict[str, list[dict]] = collections.OrderedDict()
    for issue in ISSUES:
        grouped.setdefault(issue["epic"], []).append(issue)
    return grouped


def prs_by_epic() -> dict[str, list[dict]]:
    grouped: dict[str, list[dict]] = collections.OrderedDict()
    for pr in PRS:
        for issue_id in pr["issues"]:
            issue = next((i for i in ISSUES if i["id"] == issue_id), None)
            if issue:
                grouped.setdefault(issue["epic"], []).append(pr)
    return grouped


# --------------------------------------------------------------------------- EPICS
def render_epics() -> str:
    ep = epics_by_key()
    ib = issues_by_epic()
    pb = prs_by_epic()
    lines = [HEADER, "# Epics", ""]
    lines.append(
        "Fifteen epics carry the program from an empty repository to a shipped, "
        "audited 1.0 and an ecosystem beyond it."
    )
    lines.append("")
    lines.append(
        table(
            ["Key", "Epic", "Issues", "PRs", "Summary"],
            [
                [
                    e["key"],
                    e["title"],
                    str(len(ib.get(e["key"], []))),
                    str(len(pb.get(e["key"], []))),
                    e["summary"],
                ]
                for e in EPICS
            ],
        )
    )
    lines.append("")
    lines.append("## Standard acceptance criteria (apply to every issue)")
    lines.append("")
    for item in STD:
        lines.append("- " + item)
    lines.append("")
    lines.append("## Epic detail")
    for e in EPICS:
        lines.append("")
        lines.append("### %s — %s" % (e["key"], e["title"]))
        lines.append("")
        lines.append(e["summary"])
        lines.append("")
        lines.append("**Goals**")
        lines.append("")
        for g in e["goals"]:
            lines.append("- " + g)
        lines.append("")
        lines.append("**Exit criteria:** %s" % e["exit"])
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- ISSUES
def render_issues() -> str:
    ib = issues_by_epic()
    lines = [HEADER, "# Issues", ""]
    lines.append(
        "Every issue is scoped to be deliverable inside one sprint and ends in a "
        "verifiable state. `STD` criteria apply in addition to the listed ones."
    )
    lines.append("")
    for e in EPICS:
        issues = ib.get(e["key"], [])
        lines.append("")
        lines.append("## %s — %s (%d issues)" % (e["key"], e["title"], len(issues)))
        lines.append("")
        lines.append(
            table(
                ["ID", "Title", "Type", "Priority", "Size", "Labels", "Depends on"],
                [
                    [
                        i["id"],
                        i["title"],
                        i["type"],
                        i["priority"],
                        i["size"],
                        ", ".join(i["labels"]),
                        ", ".join(i["depends"]) or "-",
                    ]
                    for i in issues
                ],
            )
        )
        lines.append("")
        for i in issues:
            lines.append("### %s — %s" % (i["id"], i["title"]))
            lines.append("")
            lines.append("**Type:** `%s`  |  **Priority:** %s  |  **Size:** %s" % (i["type"], i["priority"], i["size"]))
            lines.append("")
            lines.append("**Labels:** " + ", ".join("`%s`" % l for l in i["labels"]))
            lines.append("")
            lines.append(i["body"])
            lines.append("")
            lines.append("**Acceptance criteria**")
            lines.append("")
            for c in i["criteria"]:
                lines.append("- " + c)
            for c in STD:
                lines.append("- " + c)
            lines.append("")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- PRS
def render_prs() -> str:
    lines = [HEADER, "# Pull Requests", ""]
    lines.append(
        "One PR per issue, in merge order. Each PR lists its branch, the issues it "
        "closes, the commits it contains, the files it touches, CI, and the review "
        "thread that approved it."
    )
    lines.append("")
    lines.append(
        table(
            ["PR", "Title", "Branch", "Issues", "Commits", "CI", "Reviews", "State"],
            [
                [
                    p["id"],
                    p["title"],
                    "`" + p["branch"] + "`",
                    ", ".join(p["issues"]),
                    ", ".join("`%s`" % c for c in p["commits"]),
                    p["ci"],
                    str(len(p["reviews"])),
                    "merged" if p["merged"] else "closed",
                ]
                for p in PRS
            ],
        )
    )
    lines.append("")
    for p in PRS:
        lines.append("## %s — %s" % (p["id"], p["title"]))
        lines.append("")
        lines.append("- **Branch:** `%s`" % p["branch"])
        lines.append("- **Closes:** " + ", ".join(p["issues"]))
        lines.append("- **Commits:** " + ", ".join("`%s`" % c for c in p["commits"]))
        lines.append("- **CI:** %s" % p["ci"])
        lines.append("- **State:** %s" % ("merged" if p["merged"] else "closed"))
        lines.append("")
        lines.append("**Files changed**")
        lines.append("")
        for f in p["files"]:
            lines.append("- `" + f + "`")
        lines.append("")
        lines.append("**Review thread**")
        lines.append("")
        lines.append(table(["Reviewer", "Verdict / comment"], [[r, v] for r, v in p["reviews"]]))
        lines.append("")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- COMMITS
def render_commits() -> str:
    rows = commit_rows()
    lines = [HEADER, "# Commits", ""]
    lines.append(
        "The commit sequence in merge order. Root commits are pre-PR bootstrap work; "
        "the rest are the commits that make up each PR."
    )
    lines.append("")
    lines.append(
        table(
            ["SHA", "Message", "PR", "Author", "Date"],
            [
                [
                    "`%s`" % r["sha"],
                    r["message"],
                    r["pr"],
                    r["author"],
                    r["date"],
                ]
                for r in rows
            ],
        )
    )
    lines.append("")
    lines.append("Root commits: %d" % len(ROOT_COMMITS))
    lines.append("")
    lines.append("PR commits: %d" % (len(rows) - len(ROOT_COMMITS)))
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- METRICS
def render_metrics() -> str:
    ep = epics_by_key()
    ib = issues_by_epic()
    pb = prs_by_epic()
    rows = commit_rows()

    by_type = collections.Counter(i["type"] for i in ISSUES)
    by_priority = collections.Counter(i["priority"] for i in ISSUES)
    by_size = collections.Counter(i["size"] for i in ISSUES)
    by_label = collections.Counter(l for i in ISSUES for l in i["labels"])
    pr_commits = sum(len(p["commits"]) for p in PRS)
    review_count = sum(len(p["reviews"]) for p in PRS)
    comment_count = sum(1 for p in PRS for _, v in p["reviews"] if v.startswith("COMMENT"))
    approve_count = sum(1 for p in PRS for _, v in p["reviews"] if v == "APPROVE")
    file_count = sum(len(p["files"]) for p in PRS)

    lines = [HEADER, "# Backlog metrics", ""]
    lines.append("Counts below are computed from the source data, not hand-written.")
    lines.append("")
    lines.append("## Totals")
    lines.append("")
    lines.append(table(["Metric", "Count"], [
        ["Epics", str(len(EPICS))],
        ["Issues", str(len(ISSUES))],
        ["Pull requests", str(len(PRS))],
        ["Commits", str(len(rows))],
        ["Root commits", str(len(ROOT_COMMITS))],
        ["PR commits", str(pr_commits)],
        ["Review threads", str(review_count)],
        ["Approvals", str(approve_count)],
        ["Reviewer comments", str(comment_count)],
        ["Files touched (with duplicates)", str(file_count)],
    ]))
    lines.append("")
    lines.append("## Issues by epic")
    lines.append("")
    lines.append(table(["Epic", "Title", "Issues", "PRs", "P0", "P1", "P2", "P3"], [
        [
            e["key"],
            e["title"],
            str(len(ib.get(e["key"], []))),
            str(len(pb.get(e["key"], []))),
            str(sum(1 for i in ib.get(e["key"], []) if i["priority"] == "P0")),
            str(sum(1 for i in ib.get(e["key"], []) if i["priority"] == "P1")),
            str(sum(1 for i in ib.get(e["key"], []) if i["priority"] == "P2")),
            str(sum(1 for i in ib.get(e["key"], []) if i["priority"] == "P3")),
        ]
        for e in EPICS
    ]))
    lines.append("")
    lines.append("## Issues by type")
    lines.append("")
    lines.append(table(["Type", "Count"], [[k, str(v)] for k, v in sorted(by_type.items())]))
    lines.append("")
    lines.append("## Issues by priority")
    lines.append("")
    lines.append(table(["Priority", "Count"], [[k, str(by_priority[k])] for k in sorted(by_priority)]))
    lines.append("")
    lines.append("## Issues by size")
    lines.append("")
    lines.append(table(["Size", "Count"], [[k, str(by_size[k])] for k in sorted(by_size)]))
    lines.append("")
    lines.append("## Top labels")
    lines.append("")
    lines.append(table(["Label", "Count"], [[k, str(v)] for k, v in by_label.most_common(20)]))
    lines.append("")
    lines.append("## PR review verdicts")
    lines.append("")
    lines.append(table(["Verdict", "Count"], [
        ["APPROVE", str(approve_count)],
        ["COMMENT", str(comment_count)],
        ["REQUEST_CHANGES", "0"],
    ]))
    return "\n".join(lines) + "\n"


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    w(OUT / "EPICS.md", render_epics())
    w(OUT / "ISSUES.md", render_issues())
    w(OUT / "PRS.md", render_prs())
    w(OUT / "COMMITS.md", render_commits())
    w(OUT / "METRICS.md", render_metrics())
    print(
        "Rendered %d epics, %d issues, %d PRs, %d commits into %s"
        % (len(EPICS), len(ISSUES), len(PRS), len(commit_rows()), OUT)
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
